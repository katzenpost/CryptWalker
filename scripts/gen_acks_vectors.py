"""Acks field vectors from katzenqt's Python codec (``katzenqt/ack_codec.py``):
the count less one, the roster indexes as a list or bitmap, then one
little-endian Idx64 per member. The Go and Rust codecs do not implement this
layout, so the Python codec is the reference.

    python3 scripts/gen_acks_vectors.py KATZENQT_DIR > testdata/acks_vectors.json

Seeded, so the output depends only on the codec.
"""

import json
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(sys.argv[1]) / "src"))
from katzenqt import ack_codec  # noqa: E402

rng = random.Random(166)


def idx64() -> int:
    return rng.choice([0, 1, 2**64 - 1, rng.getrandbits(64), rng.getrandbits(16)])


valid = []
for roster in (1, 8, 9, 32, 100, 256):
    for count in sorted({1, 2, 3, roster // 4, roster // 2, roster - 1, roster} - {0}):
        indexes = sorted(rng.sample(range(roster), min(count, roster)))
        acks = {i: idx64() for i in indexes}
        field = ack_codec.encode(acks)
        assert ack_codec.decode(field) == acks
        valid.append({
            "name": f"random-{roster}-{len(acks)}",
            "acks": [[i, acks[i]] for i in rng.sample(indexes, len(indexes))],
            "field": field.hex(),
        })
for name, indexes in (("list-wins", [0, 255]), ("bitmap-wins", list(range(9))),
                      ("tie-is-list", [0, 7, 15]), ("every-member", list(range(256)))):
    acks = {i: idx64() for i in indexes}
    valid.append({"name": name, "acks": [[i, v] for i, v in acks.items()],
                  "field": ack_codec.encode(acks).hex()})

# Fields the spec's parser accepts though the encoder never writes them: a
# list where the bitmap is shorter. A strict parser refuses them.
lenient = []
for name, field in (("list-where-bitmap-shorter", bytes([2, 0, 1, 2]) + bytes(24)),
                    ("long-list", bytes([8]) + bytes(range(9)) + bytes(72))):
    acks = ack_codec.decode(field)
    assert ack_codec.encode(acks) != field
    lenient.append({"name": name, "field": field.hex(), "acks": [[i, v] for i, v in acks.items()]})

malformed = []
for name, field in (
    ("count-without-values", bytes([0])),
    ("short-of-its-count", bytes([1, 3]) + bytes(8)),
    ("more-naming-than-values", bytes([0, 2, 3]) + bytes(8)),
    ("list-descending", bytes([1, 5, 3]) + bytes(16)),
    ("list-repeated", bytes([1, 5, 5]) + bytes(16)),
    ("bitmap-ends-in-zero", bytes([2, 0xE0, 0]) + bytes(24)),
    ("bitmap-names-too-few", bytes([3, 0xE0]) + bytes(32)),
    ("bitmap-names-too-many", bytes([1, 0xE0]) + bytes(16)),
    ("bitmap-too-long", bytes([33]) + bytes([0xFF] * 33) + bytes(8 * 34)),
):
    try:
        ack_codec.decode(field)
    except ack_codec.AcksError as error:
        malformed.append({"name": name, "field": field.hex(), "error": str(error)})
    else:
        raise AssertionError(f"{name} decoded")

json.dump({
    "about": "Acks fields in the counted layout: the count less one, the roster indexes as a "
             "list or bitmap, then one little-endian Idx64 per member. Generated by "
             "scripts/gen_acks_vectors.py from katzenqt's Python codec (ack_codec.py). Each valid "
             "case lists (roster index, Idx64) pairs in the order the sender was given them. "
             "Lenient fields are accepted by the spec's parser but never written by the encoder; "
             "malformed fields are refused.",
    "valid": valid,
    "lenient": lenient,
    "malformed": malformed,
}, sys.stdout, indent=1)
print()
